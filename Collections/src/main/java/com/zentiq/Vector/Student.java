package com.zentiq.Vector;

public class Student {

    String name;
    int age;
    double marks;
    char grade;
    String city;

    public Student(String name, int age, double marks, char grade, String city) {
        this.name = name;
        this.age = age;
        this.marks = marks;
        this.grade = grade;
        this.city = city;
    }
}
